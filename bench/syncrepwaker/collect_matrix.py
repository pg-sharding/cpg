#!/usr/bin/env python3
"""Collect a completed matrix into compact results and environment JSON."""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re

from compare_bench import write_json


def checkpoint_events(path):
    events = []
    for line in path.read_text().splitlines():
        kind = next((text for text in ("checkpoint starting:", "checkpoint complete:",
                                      "restartpoint starting:", "restartpoint complete:")
                     if text in line), None)
        if kind:
            match = re.match(r"^(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d\.\d+) UTC ", line)
            if match:
                instant = datetime.fromisoformat(match[1]).replace(tzinfo=timezone.utc).timestamp()
                events.append((instant, kind))
    return events


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--baseline-commit")
    parser.add_argument("--feature-commit")
    parser.add_argument("--harness-commit")
    args = parser.parse_args()
    root = args.output.resolve()
    state = json.loads((root / "state.json").read_text())
    if state["status"] != "complete":
        raise RuntimeError("matrix is not complete")
    date = datetime.fromtimestamp(state["started_epoch"], timezone.utc).date().isoformat()
    environment = {
        "date_utc": date, "baseline_commit": args.baseline_commit,
        "feature_algorithm_commit": args.feature_commit, "harness_commit": args.harness_commit,
        "matrix_state": state, "phases": {}, "calibration_rows": [],
        "host": {"uname": list(os.uname()), "cpu_affinity": sorted(os.sched_getaffinity(0)),
                 "cpu_model": next(line.split(":", 1)[1].strip()
                                   for line in Path("/proc/cpuinfo").read_text().splitlines()
                                   if line.startswith("model name")),
                 "meminfo": Path("/proc/meminfo").read_text()},
        "notes": [
            "Main quantiles describe transactions completed within each timed window.",
            "Summaries use medians of per-run quantiles, not pooled transaction quantiles.",
            "The on control has direct limit 0; hybrid8 explicitly selects limit 8.",
            "Read/write mixed-script statistics are retained separately.",
            "Process CPU covers both servers and the client; it cannot be assigned to a script class.",
            "Primary, standby and client share one VM and one persistent storage volume.",
            "Large INSERT payloads and batch rows are generated by SQL on the server.",
            "TLS encrypts client protocol and the replication WAL stream.",
            "Per-transaction gzip logs and original JSON rows remain in the phase output directories."
        ]}
    rows, unique = [], set()
    for name, phase in state["phases"].items():
        if phase["status"] != "complete":
            raise RuntimeError(f"incomplete phase: {name}")
        output = Path(phase["output"])
        source = json.loads((output / "results.json").read_text())
        if len(source) != phase["expected_rows"]:
            raise RuntimeError(f"unexpected row count in {name}")
        metadata = json.loads((output / "metadata.json").read_text())
        metadata["primary_config"] = "\n".join(
            line for line in metadata["primary_config"].splitlines()
            if line.strip() and not line.lstrip().startswith("#")) + "\n"
        if metadata["postgres_sha256"] != state["fingerprint"]["binary_sha256"]:
            # Harness calls its candidate "feature"; the matrix fingerprint
            # uses the same role name.
            raise RuntimeError(f"binary hashes differ in {name}")
        environment["phases"][name] = metadata
        events = {side: checkpoint_events(output / (side + ".log"))
                  for side in ("primary", "standby")}
        for row in source:
            key = (name, row["case"]["name"], row["variant"], row["repeat"])
            if key in unique:
                raise RuntimeError(f"duplicate row: {key}")
            unique.add(key)
            if (row["failed"] or row["skipped"] or row["missing_cpu_pids"] or
                    row.get("diagnostic") or row.get("interference")):
                raise RuntimeError(f"invalid measured row: {key}")
            if abs(row["end_epoch"] - row["start_epoch"] - row["elapsed_seconds"]) > .01:
                raise RuntimeError(f"wall/monotonic clock mismatch: {key}")
            if sum(group["latency"]["count"] for group in row["by_script"].values()) != row["latency"]["count"]:
                raise RuntimeError(f"script counts differ: {key}")
            if row["initial_history_rows"] not in (None, 0):
                raise RuntimeError(f"snapshot was not restored: {key}")
            row["checkpoint_events"] = {
                side: {kind: sum(row["start_epoch"] <= instant < row["end_epoch"] and event == kind
                                 for instant, event in values)
                       for kind in sorted({event for _, event in values})}
                for side, values in events.items()}
            row["dataset"] = name
            for field in ("pids", "command", "log_files"):
                row.pop(field, None)
            row["cpu"] = {role: {"cpu_seconds": metrics["cpu_seconds"]}
                          for role, metrics in row["cpu"].items() if metrics["cpu_seconds"]}
            row["missing_cpu_count"] = len(row.pop("missing_cpu_pids"))
            if name.startswith("calibrate-"):
                environment["calibration_rows"].append(row)
            else:
                rows.append(row)
    if len(rows) != state["expected_main_rows"]:
        raise RuntimeError("incomplete main matrix")
    environment["main_measured_transactions"] = sum(row["latency"]["count"] for row in rows)
    write_json(root / f"workload-results-{date}.json", rows)
    write_json(root / f"workload-environment-{date}.json", environment)
    print(json.dumps({"runs": len(rows), "transactions": environment["main_measured_transactions"],
                      "calibration_runs": len(environment["calibration_rows"])}))


if __name__ == "__main__":
    main()
